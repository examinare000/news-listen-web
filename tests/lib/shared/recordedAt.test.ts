// @vitest-environment node
// 記録時刻の読み（ISO 8601・小数 0〜9 桁・Z / ±hh:mm をミリ秒に切り捨てる）。I/O なし。
//
// RED 理由（実装前）: `@/lib/shared/recordedAt` がまだ存在しない。
import { describe, expect, test } from 'vitest'
import { parseRecordedAt } from '@/lib/shared/recordedAt'

const BASE = Date.UTC(2026, 10, 16, 0, 0, 1) // 2026-11-16T00:00:01Z

describe('shared-sync-09: 小数 0〜9 桁と Z・±hh:mm をミリ秒に切り捨てて読む。送りは小数 3 桁・Z', () => {
  test.each<[string, string, number]>([
    ['小数 6 桁・Z', '2026-11-16T00:00:01.123456Z', BASE + 123],
    ['小数 9 桁・+00:00', '2026-11-16T00:00:01.123456789+00:00', BASE + 123],
    ['小数なし・Z', '2026-11-16T00:00:01Z', BASE],
    ['小数 1 桁', '2026-11-16T00:00:01.5Z', BASE + 500],
    ['小数 3 桁', '2026-11-16T00:00:01.123Z', BASE + 123],
    ['小数 4 桁以上は丸めず切り捨てる（.9999 → 999）', '2026-11-16T00:00:01.9999Z', BASE + 999],
    ['小数 9 桁の末尾 9 も切り捨て', '2026-11-16T00:00:01.999999999Z', BASE + 999],
    ['+09:00 は UTC へ換算する', '2026-11-16T09:00:01+09:00', BASE],
    ['-05:30 は UTC へ換算する', '2026-11-15T18:30:01.250-05:30', BASE + 250],
  ])('%s', (_name, text, expected) => {
    expect(parseRecordedAt(text)).toBe(expected)
  })

  test('送りの書式（new Date(ms).toISOString()）で出した文字列は同じミリ秒で往復する', () => {
    const ms = BASE + 123
    expect(parseRecordedAt(new Date(ms).toISOString())).toBe(ms)
  })

  test.each<[string, string]>([
    ['タイムゾーンなし', '2026-11-16T00:00:01'],
    ['タイムゾーンなし・小数あり', '2026-11-16T00:00:01.123456'],
    ['空文字', ''],
    ['壊れた文字列', 'not a date'],
    ['日付だけ', '2026-11-16'],
    ['区切りが空白', '2026-11-16 00:00:01Z'],
    ['暦として不正な月', '2026-13-16T00:00:01Z'],
    ['暦として不正な日', '2026-02-30T00:00:01Z'],
    ['暦として不正な時', '2026-11-16T25:00:01Z'],
    ['小数の桁が 10 桁以上', '2026-11-16T00:00:01.1234567890Z'],
    ['小数点だけで桁なし', '2026-11-16T00:00:01.Z'],
    ['前後に余計な文字', ' 2026-11-16T00:00:01Z '],
    ['オフセットの形が違う（+0900）', '2026-11-16T09:00:01+0900'],
  ])('読めない値は null: %s', (_name, text) => {
    expect(parseRecordedAt(text)).toBeNull()
  })
})
